using System.Text;
using System.Text.Json.Nodes;
using Microsoft.Extensions.Logging;
using HushMusic.Core.Lyrics;
using HushMusic.InnerTube.Parsing.Common;

namespace HushMusic.InnerTube.Parsing;

/// <summary>One caption track of a video (<c>player</c> response, <c>captions.playerCaptionsTracklistRenderer.captionTracks[]</c>).</summary>
internal sealed record CaptionTrack(string BaseUrl, string LanguageCode, string? Name, bool IsAutoGenerated)
{
    /// <summary>
    /// The URL carries <c>exp=xpe</c>: YouTube then answers only with a proof-of-origin token, which the app doesn't
    /// have, so the track is left out.
    /// </summary>
    public bool NeedsPoToken => BaseUrl.Contains("exp=xpe", StringComparison.Ordinal);
}

/// <summary>
/// A video's captions read as lyrics. Not in ytmusicapi: the caption list is part of the same <c>player</c> response
/// the app already reads for loudness, and each track's <c>baseUrl</c> (www.youtube.com/api/timedtext) returns the
/// cues as json3 (<c>events[]</c> of <c>tStartMs</c>, <c>dDurationMs</c> and <c>segs[].utf8</c>) with <c>&amp;fmt=json3</c>.
/// </summary>
internal static class CaptionsParser
{
    private const string Page = "Captions";

    /// <summary>The video's caption tracks; empty when it has none.</summary>
    public static IReadOnlyList<CaptionTrack> ParseTracks(JsonNode playerResponse)
    {
        ArgumentNullException.ThrowIfNull(playerResponse);
        var tracks = new List<CaptionTrack>();
        foreach (var track in playerResponse.Arr("captions", "playerCaptionsTracklistRenderer", "captionTracks").Objects())
        {
            var baseUrl = track.Str("baseUrl");
            var language = track.Str("languageCode");
            if (string.IsNullOrEmpty(baseUrl) || string.IsNullOrEmpty(language))
            {
                continue;
            }

            tracks.Add(new CaptionTrack(baseUrl, language, TextRuns.Text(track.Obj("name")), track.Str("kind") == "asr"));
        }

        return tracks;
    }

    /// <summary>
    /// The track to read as lyrics: written by a person (not auto-generated, <c>kind != "asr"</c>) and in the song's
    /// language. That language is the auto-generated track's, which follows what is sung; without one, the video's only
    /// language is taken (unconfirmed). Null when there is no such track or the language can't be told.
    /// </summary>
    public static (CaptionTrack Track, bool LanguageConfirmed)? PickLyricsTrack(IReadOnlyList<CaptionTrack> tracks)
    {
        ArgumentNullException.ThrowIfNull(tracks);
        var written = tracks.Where(t => !t.IsAutoGenerated && !t.NeedsPoToken).ToList();
        if (written.Count == 0)
        {
            return null;
        }

        if (tracks.FirstOrDefault(t => t.IsAutoGenerated) is { } spoken)
        {
            var match = written.FirstOrDefault(t => string.Equals(t.LanguageCode, spoken.LanguageCode, StringComparison.OrdinalIgnoreCase))
                ?? written.FirstOrDefault(t => BaseLanguage(t.LanguageCode) == BaseLanguage(spoken.LanguageCode));
            return match is null ? null : (match, true);
        }

        var languages = tracks.Where(t => !t.IsAutoGenerated).Select(t => BaseLanguage(t.LanguageCode)).Distinct().Count();
        return languages == 1 ? (written[0], false) : null;
    }

    /// <summary>The track's URL asking for json3 (any other <c>fmt</c> replaced). Null when it isn't an absolute https URL.</summary>
    public static Uri? Json3Url(string baseUrl)
    {
        if (!Uri.TryCreate(baseUrl, UriKind.Absolute, out var uri) || uri.Scheme != Uri.UriSchemeHttps)
        {
            return null;
        }

        // The query is kept as sent (already escaped, and signed).
        var query = uri.Query.TrimStart('?')
            .Split('&', StringSplitOptions.RemoveEmptyEntries)
            .Where(p => !p.StartsWith("fmt=", StringComparison.Ordinal))
            .Append("fmt=json3");
        return new Uri(uri.GetLeftPart(UriPartial.Path) + "?" + string.Join('&', query));
    }

    /// <summary>
    /// The cues of a json3 caption file as lines: the segments of each event joined, line breaks inside a cue turned
    /// into spaces, start and end from <c>tStartMs</c> and <c>dDurationMs</c>. Text is left as written (notes,
    /// "[Music]"): <see cref="LyricsCleanup.Timed"/> deals with it.
    /// </summary>
    public static IReadOnlyList<LyricLine> ParseJson3(JsonNode json, ILogger logger)
    {
        ArgumentNullException.ThrowIfNull(json);
        var events = json.Arr("events");
        if (events is null)
        {
            new ParseScope(logger, Page).IgnoreItem(json.Describe(), "no events");
            return [];
        }

        var lines = new List<LyricLine>(events.Count);
        foreach (var cue in events.Objects())
        {
            // Window and style definitions have no segments.
            if (cue.Arr("segs") is not { } segments || cue.Long("tStartMs") is not { } startMs)
            {
                continue;
            }

            var text = new StringBuilder();
            foreach (var segment in segments.Objects())
            {
                text.Append(segment.Str("utf8"));
            }

            var line = text.ToString().Replace('\n', ' ');
            if (string.IsNullOrWhiteSpace(line))
            {
                continue;
            }

            var start = TimeSpan.FromMilliseconds(startMs);
            var durationMs = cue.Long("dDurationMs") ?? 0;
            var end = durationMs > 0 ? start + TimeSpan.FromMilliseconds(durationMs) : start;

            // aAppend continues the previous cue (rolling captions).
            if (cue.Long("aAppend") == 1 && lines.Count > 0)
            {
                var previous = lines[^1];
                lines[^1] = previous with { Text = previous.Text + line, End = end > previous.End ? end : previous.End };
                continue;
            }

            lines.Add(new LyricLine(start, end, line, []));
        }

        return lines;
    }

    private static string BaseLanguage(string code)
    {
        var dash = code.IndexOfAny(['-', '_']);
        return (dash > 0 ? code[..dash] : code).ToLowerInvariant();
    }
}
