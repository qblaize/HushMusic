using System.Text.Json.Nodes;
using HushMusic.Core.Lyrics;
using HushMusic.InnerTube.Parsing;
using Xunit;

namespace HushMusic.InnerTube.Tests.Parsing;

/// <summary>
/// Caption tracks and json3 cues. The player responses in Fixtures/Captions were captured anonymously on 2026-10-20
/// (cut down to their caption parts); the caption files keep the shape and timings of real json3 files, with the text
/// replaced by placeholder lines.
/// </summary>
public sealed class CaptionsParserTests
{
    private static JsonNode Load(string name) => ParserFixtures.Load(Path.Combine("Captions", name));

    [Fact]
    public void Tracks_are_read_with_language_name_and_kind()
    {
        var tracks = CaptionsParser.ParseTracks(Load("player_captions_asr.json"));

        Assert.Equal(6, tracks.Count);
        Assert.Equal(["en", "en", "de-DE", "ja", "pt-BR", "es-419"], tracks.Select(t => t.LanguageCode));
        Assert.Equal("English", tracks[0].Name);
        Assert.False(tracks[0].IsAutoGenerated);
        Assert.True(tracks[1].IsAutoGenerated);
        Assert.Equal("English (auto-generated)", tracks[1].Name);
        Assert.StartsWith("https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ", tracks[0].BaseUrl, StringComparison.Ordinal);
        Assert.All(tracks, t => Assert.False(t.NeedsPoToken));
    }

    [Fact]
    public void A_song_without_captions_has_no_tracks()
    {
        Assert.Empty(CaptionsParser.ParseTracks(Load("player_captions_none.json")));
    }

    [Fact]
    public void The_written_track_in_the_auto_generated_tracks_language_is_picked_and_confirmed()
    {
        var picked = CaptionsParser.PickLyricsTrack(CaptionsParser.ParseTracks(Load("player_captions_asr.json")));

        Assert.NotNull(picked);
        Assert.Equal("en", picked.Value.Track.LanguageCode);
        Assert.False(picked.Value.Track.IsAutoGenerated);
        Assert.True(picked.Value.LanguageConfirmed);
    }

    [Fact]
    public void A_video_with_one_written_language_uses_it_unconfirmed()
    {
        var picked = CaptionsParser.PickLyricsTrack(CaptionsParser.ParseTracks(Load("player_captions_single.json")));

        Assert.NotNull(picked);
        Assert.Equal("en", picked.Value.Track.LanguageCode);
        Assert.False(picked.Value.LanguageConfirmed);
    }

    [Fact]
    public void Several_written_languages_without_an_auto_generated_track_are_ambiguous()
    {
        // Despacito: en, en-US, ja, es, es-ES; nothing says which one is sung.
        Assert.Null(CaptionsParser.PickLyricsTrack(CaptionsParser.ParseTracks(Load("player_captions_multilingual.json"))));
    }

    [Fact]
    public void Only_auto_generated_captions_are_never_used()
    {
        var tracks = CaptionsParser.ParseTracks(Load("player_captions_asr_only.json"));

        Assert.Single(tracks);
        Assert.Null(CaptionsParser.PickLyricsTrack(tracks));
    }

    [Fact]
    public void A_written_track_in_another_language_than_the_sung_one_is_not_used()
    {
        CaptionTrack[] tracks =
        [
            new("https://www.youtube.com/api/timedtext?v=x&lang=en", "en", "English", false),
            new("https://www.youtube.com/api/timedtext?v=x&kind=asr&lang=ko", "ko", "Korean (auto-generated)", true),
        ];

        Assert.Null(CaptionsParser.PickLyricsTrack(tracks));
    }

    [Fact]
    public void A_regional_written_track_matches_the_spoken_base_language()
    {
        CaptionTrack[] tracks =
        [
            new("https://www.youtube.com/api/timedtext?v=x&lang=es-419", "es-419", "Spanish (Latin America)", false),
            new("https://www.youtube.com/api/timedtext?v=x&kind=asr&lang=es", "es", "Spanish (auto-generated)", true),
        ];

        Assert.Equal("es-419", CaptionsParser.PickLyricsTrack(tracks)?.Track.LanguageCode);
    }

    [Fact]
    public void Tracks_that_need_a_proof_of_origin_token_are_skipped()
    {
        CaptionTrack[] tracks = [new("https://www.youtube.com/api/timedtext?v=x&exp=xpe&lang=en", "en", "English", false)];

        Assert.True(tracks[0].NeedsPoToken);
        Assert.Null(CaptionsParser.PickLyricsTrack(tracks));
    }

    [Fact]
    public void The_json3_url_keeps_the_signed_query_and_replaces_the_format()
    {
        var url = CaptionsParser.Json3Url("https://www.youtube.com/api/timedtext?v=x&sparams=ip,ipbits&signature=A.B&fmt=srv3&lang=en");

        Assert.NotNull(url);
        Assert.Equal("https://www.youtube.com/api/timedtext?v=x&sparams=ip,ipbits&signature=A.B&lang=en&fmt=json3", url.AbsoluteUri);
        Assert.Null(CaptionsParser.Json3Url("http://www.youtube.com/api/timedtext?v=x"));
        Assert.Null(CaptionsParser.Json3Url("/api/timedtext?v=x"));
    }

    [Fact]
    public void Json3_cues_become_lines_with_start_and_end()
    {
        var log = new CapturingLogger();
        var lines = CaptionsParser.ParseJson3(Load("timedtext_sample_en.json"), log);

        Assert.Equal(10, lines.Count);
        Assert.Equal("[♪♪♪]", lines[0].Text);
        Assert.Equal(TimeSpan.FromMilliseconds(18640), lines[1].Start);
        Assert.Equal(TimeSpan.FromMilliseconds(18640 + 3240), lines[1].End);
        Assert.Equal("♪ Line one of the test song ♪", lines[1].Text);

        // A line break inside a cue is a space.
        Assert.Equal("♪ Second test line with a break inside ♪", lines[2].Text);
        Assert.All(lines, l => Assert.Empty(l.Words));
        Assert.Empty(log.Warnings);
    }

    [Fact]
    public void Window_definitions_are_skipped_and_appended_cues_join_the_previous_one()
    {
        var json = JsonNode.Parse("""
            {"events":[
              {"tStartMs":0,"dDurationMs":99000,"id":1,"wpWinPosId":1,"wsWinStyleId":1},
              {"tStartMs":1000,"dDurationMs":2000,"wWinId":1,"segs":[{"utf8":"Hello"},{"utf8":" world","tOffsetMs":500}]},
              {"tStartMs":2500,"dDurationMs":1500,"wWinId":1,"aAppend":1,"segs":[{"utf8":" again"}]},
              {"tStartMs":5000,"segs":[{"utf8":"\n"}]},
              {"tStartMs":6000,"dDurationMs":1000,"segs":[{"utf8":"Next"}]}
            ]}
            """)!;

        var lines = CaptionsParser.ParseJson3(json, new CapturingLogger());

        Assert.Equal(2, lines.Count);
        Assert.Equal("Hello world again", lines[0].Text);
        Assert.Equal(TimeSpan.FromSeconds(1), lines[0].Start);
        Assert.Equal(TimeSpan.FromSeconds(4), lines[0].End);
        Assert.Equal("Next", lines[1].Text);
    }

    [Fact]
    public void Cleaned_captions_lose_notes_sound_descriptions_and_shouting()
    {
        var raw = CaptionsParser.ParseJson3(Load("timedtext_sample_multiline_en.json"), new CapturingLogger());

        var lines = LyricsCleanup.Timed(raw, TimeSpan.FromSeconds(200), LyricsTextKind.Captions);

        // The first cue is only notes (the intro); the text was all capitals.
        Assert.Equal(9, lines.Count);
        Assert.Equal("I've got a test line", lines[0].Text);
        Assert.Equal(TimeSpan.FromMilliseconds(49200), lines[0].Start);
        Assert.Equal("I'm the second line of the sample", lines[1].Text);
        Assert.Equal("Eighth line of the sample (oh)", lines[7].Text);
        Assert.All(lines.Zip(lines.Skip(1)), pair => Assert.True(pair.First.End <= pair.Second.Start));
    }
}
